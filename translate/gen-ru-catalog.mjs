// Генератор packages/ui/src/i18n/locales/ru-RU.ts из исходников.
// Использование: node gen-ru-catalog.mjs <путь к origin/ZCode-main>
// Ключи берёт из packages/ui/src/i18n/locales/en-US.ts (факт текущей версии исходников),
// значения — из ru.json; отсутствующие в словаре — английские + предупреждение.
import { fileURLToPath } from 'url';
import fs from 'fs';
import path from 'path';

const root = process.argv[2];
if (!root) { console.error('usage: node gen-ru-catalog.mjs <origin/ZCode-main>'); process.exit(1); }
const selfDir = path.dirname(fileURLToPath(import.meta.url));
const enPath = path.join(root, 'packages', 'ui', 'src', 'i18n', 'locales', 'en-US.ts');
const dictPath = path.join(selfDir, 'ru.json');
const outPath = path.join(root, 'packages', 'ui', 'src', 'i18n', 'locales', 'ru-RU.ts');

const ru = JSON.parse(fs.readFileSync(dictPath, 'utf8'));
const enSrc = fs.readFileSync(enPath, 'utf8');

// id-ключи каталога: только с точкой ("section.name"), чтобы не зацепить служебные строки
const keyRe = /"([a-zA-Z0-9_.-]+)":/g;
const keys = [...new Set([...enSrc.matchAll(keyRe)].map(m => m[1]))].filter(k => k.includes('.'));

const esc = s => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
let missing = 0;
const lines = keys.map(k => {
  const v = k in ru ? ru[k] : (missing++, '');
  return `  "${k}": "${esc(v)}",`;
});

const out =
  '// @generated by translate/gen-ru-catalog.mjs — не править вручную, правьте ru.json\n' +
  '/** Русские переводы */\n' +
  'const ruRU: Record<string, string> = {\n' + lines.join('\n') + '\n};\n\n' +
  'export default ruRU;\n';
fs.writeFileSync(outPath, out, 'utf8');
console.log(`Записано ${outPath}: ${keys.length} ключей, взято из EN (нет перевода): ${missing}`);
